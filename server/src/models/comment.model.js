import mongoose from "mongoose";

const commentSchema = new mongoose.Schema({
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true,
    },
    news: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "News",
        required: true,
    },
    body: {
        type: String,
        required: true,
    },
    createdAt: {
        type: Date,
        default: Date.now,
    },
});

const commentModel = mongoose.model("Comment", commentSchema);

export default commentModel;
